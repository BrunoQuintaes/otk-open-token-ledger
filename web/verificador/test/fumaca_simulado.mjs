// Fumaça da interface com o núcleo SIMULADO (não confere assinatura; só a tela).
import path from 'node:path';
import { RAIZ, abrirNavegador, rodarNaPagina, relatorioTap } from './lib.mjs';
const T = relatorioTap();
const html = path.join(RAIZ, 'dist/verificador-otk.SIMULADO.html');
const { browser, channel } = await abrirNavegador();
console.log('# navegador', channel);
const opts = { recibos: [path.join(RAIZ, 'test/simulado/recibos.jsonl')], chaveiro: path.join(RAIZ, 'test/simulado/chaveiro.json') };
const r = await rodarNaPagina(browser, html, opts);
console.log(JSON.stringify(r.tela, null, 1));
T.t(r.tela.linhas.length === 3, '3 linhas');
T.t(r.tela.linhas[1].join(' ').includes('<b id=injetado>'), 'texto hostil aparece como texto, não HTML');
T.t(await r.page.evaluate(() => !document.getElementById('injetado')), 'nenhum elemento injetado');
T.t(r.tela.linhas[0][4] === '12,345', 'CU 12345/1000 = 12,345', r.tela.linhas[0][4]);
T.t(r.requisicoes.length === 0, 'sem requisição', r.requisicoes.join(','));
T.t(r.erros.length === 0, 'sem erro no console', r.erros.join(' | '));
T.t(await r.page.evaluate(() => !document.getElementById('aviso-simulado').hidden), 'aviso de núcleo simulado visível');
await r.page.click('#tabela-corpo tr:nth-child(3) button');
const det = await r.page.evaluate(() => ({ open: document.getElementById('detalhe').open, a: document.getElementById('det-aconteceu').textContent, s: document.getElementById('det-significa').textContent, n: document.getElementById('det-nao-garante').textContent }));
T.t(det.open && det.a.length > 10 && det.s.length > 10 && det.n.length > 10, 'detalhe abre com 3 blocos (reserva preenche texto vazio)', JSON.stringify(det));
await r.page.keyboard.press('Escape');
T.t(!(await r.page.evaluate(() => document.getElementById('detalhe').open)), 'Esc fecha o detalhe');
await r.page.fill('#f-de', '10/11/2026'); await r.page.dispatchEvent('#f-de', 'change');
T.t((await r.page.$$('#tabela-corpo tr')).length === 1, 'filtro De 10/11/2026 (dd/mm/aaaa) deixa 1 linha');
T.t(await r.page.evaluate(() => document.getElementById('f-de').type === 'text' && document.getElementById('f-de').placeholder === 'dd/mm/aaaa'), 'campo de data é texto dd/mm/aaaa (não depende do idioma do navegador)');
await r.page.fill('#f-de', '2026-11-10'); await r.page.dispatchEvent('#f-de', 'change');
T.t((await r.page.$$('#tabela-corpo tr')).length === 3 && /dd\/mm\/aaaa/.test(await r.page.evaluate(() => document.getElementById('st-filtro').textContent)), 'data fora de dd/mm/aaaa: avisa e mostra tudo');
await r.page.fill('#f-de', '31/02/2026'); await r.page.dispatchEvent('#f-de', 'change');
T.t((await r.page.$$('#tabela-corpo tr')).length === 3, 'data impossível (31/02) é recusada');
await r.page.fill('#f-de', '10/11/2026'); await r.page.dispatchEvent('#f-de', 'change');
await r.page.screenshot({ path: path.join(RAIZ, 'dist/tela_simulado_desktop.png'), fullPage: true });
await r.context.close();
const m = await rodarNaPagina(browser, html, { ...opts, viewport: { width: 360, height: 780 }, tema: 'dark' });
T.t(m.tela.largura <= 360, 'sem rolagem horizontal a 360 px', `${m.tela.largura}`);
await m.page.screenshot({ path: path.join(RAIZ, 'dist/tela_simulado_360_escuro.png'), fullPage: true });
await m.context.close();
await browser.close();
T.fim(path.join(RAIZ, 'test/fumaca_simulado.TAP.txt'));
