/**
 * D1–D8 / S4 — INT-02 / D1-G06 (integrated) / D7-G10 / D3-G07 / D2-G05: one operation through the
 * delivered entrypoint all the way to the isolated 7-validator Besu network.
 *
 *   tsx src/api/server.ts (OTK_PROXY_ENABLED=1, profile bootstrapD1D8)
 *     → auth/tenant (OTK_TENANTS token) → durable operation in PostgreSQL BEFORE the provider
 *     → local controllable provider (SYNTHETIC, no network, no paid call)
 *     → B: normalizeUsage + computeCu (development-profile weights, flagged) + price + counter
 *     → A: opening (CSPRNG) stored → receipt v3 + conference signed (operator key)
 *     → C: outbox persist_receipt → enqueue_proof (target frozen) → proof worker (snarkjs, metering_v3)
 *     → submit_onchain → ReceiptRegistryV3 on Besu (chainId 16251), registration verified on chain.
 * No double of crypto or measurement anywhere in this path.
 *
 * Hand vector: gpt-4o-mini (model weight 0.400) × openai (1.000), usage 100 in + 20 out:
 *   CU = (100 + 20) × 400 × 1000 micro-units = 48 000 000 micro-CU = 48 CU (scale 10^6).
 *   Public bucket (otk.public_bucket.fixed@1, width 1000 CU = 10^9 micro-CU): closed [0, 10^9 − 1].
 *
 * Needs: . scripts/ops/s4_env.sh, the S4 Besu network and OTK_S4_BESU_DIR (generated by
 * tools/besu/s4_gen_besu7.mjs; dev keys of THAT network only, read from files, never printed).
 *
 * Modules under test: the whole delivered path started through `./d1d8_c_proc.ts` (API entry point, measurement,
 * signing, outbox, proof worker and on-chain submission) against the fake provider from `./d1d8_c_provider.ts` and a
 * local Besu test network.
 *
 * Strategy: a single end-to-end call checked against the hand vector above: CU, signed receipt and conference, the
 * opening stored first, the proof registered on chain, and no exact usage made public.
 *
 * Run just this file (after the setup above): `npx tsx --test test/services/d1d8_s4_int02_besu.test.ts`; it also
 * needs `OTK_TEST_PG_URL` from `test/services/d1d8_c_env.ts` and a writable temporary directory.
 *
 * @module test/services/d1d8_s4_int02_besu.test
 */
import { describe, it, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { ethers } from 'ethers';
import { createTestDb, RUN, type TestDb } from './d1d8_c_env.js';
import { startApi, killProc, eventually, type Proc } from './d1d8_c_proc.js';
import { ControllableProvider } from './d1d8_c_provider.js';
import { REGISTRY_V3_SUBMIT_ABI } from '../../src/zk/v3/index.js';

const BESU = process.env['OTK_S4_BESU_DIR'];
if (!BESU) throw new Error('OTK_S4_BESU_DIR is required (S4 Besu network directory)');
const net = JSON.parse(readFileSync(path.join(BESU, 'network.json'), 'utf8')) as { rpc: string; chainId: number };
const deployment = JSON.parse(readFileSync(path.join(BESU, 'deploy_v3_besu.json'), 'utf8')) as { domain: { registry: string; chainId: string } };
const devKey = (n: string) => `0x${readFileSync(path.join(BESU, 'dev', `${n}.key`), 'utf8').trim()}`;

let db: TestDb;
const provider = new ControllableProvider();
let api: Proc;
let proxy = '';
const T = `int02${RUN}`;
const OP = `int02-${RUN}`;
const rpc = new ethers.JsonRpcProvider(net.rpc, undefined, { staticNetwork: true });

before(async () => {
  db = await createTestDb('s4int02');
  await provider.start();
  api = await startApi({
    OTK_PROXY_ENABLED: '1', OTK_DB_URL: db.url, OTK_TENANTS: `${T}/OPERATOR:tok-${RUN}`,
    OTK_PROXY_ALLOW_UPSTREAM_OVERRIDE: '1', OTK_PROXY_UPSTREAM_OPENAI: provider.url, OPENAI_API_KEY: 'sk-otkd1d8s4-provider-fixture',
    OTK_PROXY_FORWARD_HEADERS: 'x-test-script,x-test-tokens,x-test-model', OTK_OPERATION_RECOVERY_MS: '500',
    OTK_SPOOL_DIR: mkdtempSync(path.join(tmpdir(), 'otkd1d8s4-int02-spool-')), OTK_INSTANCE_ID: `int02-${RUN}`,
    OTK_CU_WEIGHTS_PROFILE: 'development', OTK_PRICE_TABLE_FILES: 'test/fixtures/d1d8/b/price_table_illustrative_v1.json',
    OTK_V3_OPERATOR_KEY: devKey('operator'), OTK_V3_SUBMITTER_KEY: devKey('submitter'),
    OTK_V3_DEPLOYMENT_FILE: path.join(BESU, 'deploy_v3_besu.json'), OTK_V3_RPC_URL: net.rpc,
  }, { extraPorts: ['OTK_PROXY_PORT'], timeoutMs: 120_000 });
  proxy = `http://127.0.0.1:${api.extraPorts['OTK_PROXY_PORT']}`;
  assert.ok(await eventually(async () => { try { return (await fetch(`${proxy}/health`)).ok; } catch { return false; } }, 90_000, 250), api.log.join('').slice(-3000));
});
after(async () => { await killProc(api); await provider.stop(); await db.drop(); rpc.destroy(); });

describe('S4 INT-02 — entrypoint → B → A → PostgreSQL/outbox → real proof → Besu', () => {
  it('one call: hand-computed CU, signed receipt + conference, opening first, proof registered on chain, no exact usage public', async () => {
    const before = provider.calls.length;
    const r = await fetch(`${proxy}/v1/chat/completions`, {
      method: 'POST',
      headers: { 'content-type': 'application/json', authorization: `Bearer tok-${RUN}`, 'x-otk-operation-id': OP, 'x-test-script': 'ok', 'x-test-tokens': '100,20', 'x-test-model': 'gpt-4o-mini-2024-07-18' },
      body: JSON.stringify({ model: 'gpt-4o-mini', messages: [{ role: 'user', content: 'Say hello.' }], max_tokens: 64 }),
    });
    assert.equal(r.status, 200);
    await r.text();
    assert.equal(provider.calls.length, before + 1);

    // durable operation, exact CU
    assert.ok(await eventually(async () => (await db.pool.query("SELECT 1 FROM otk_operations WHERE tenant_id = $1 AND operation_id = $2 AND reservation->>'state' = 'settled'", [T, OP])).rowCount === 1, 30_000));
    const row = (await db.pool.query<{ cu: { units: string; scale: string }; dev: boolean }>("SELECT reservation->'cu' AS cu, (config->>'developmentProfile')::boolean AS dev FROM otk_operations WHERE tenant_id = $1 AND operation_id = $2", [T, OP])).rows[0]!;
    assert.deepEqual(row.cu, { units: '48000000', scale: '1000000' }, 'hand vector: 48 CU');
    assert.equal(row.dev, true, 'development-profile weights are flagged in the operation');

    // opening stored BEFORE the proof job (created_at ordering), receipt v3 + conference signed
    assert.ok(await eventually(async () => (await db.pool.query("SELECT 1 FROM otk_outbox WHERE tenant_id = $1 AND operation_id = $2 AND kind = 'enqueue_proof'", [T, OP])).rowCount === 1, 60_000));
    const order = (await db.pool.query<{ o: Date; j: Date }>("SELECT (SELECT created_at FROM otk_openings WHERE tenant_id = $1 AND operation_id = $2) AS o, (SELECT created_at FROM otk_outbox WHERE tenant_id = $1 AND operation_id = $2 AND kind = 'enqueue_proof') AS j", [T, OP])).rows[0]!;
    assert.ok(order.o.getTime() <= order.j.getTime(), 'opening persisted before enqueue_proof');
    const exp = await (await fetch(`${proxy}/v1/operations/${OP}/conference`, { headers: { authorization: `Bearer tok-${RUN}` } })).json() as {
      receipt: { payload: { cu: { cu: { units: string } }; publicCommitment: string; config: { circuitId: string } } }; conference: { payload?: { state: string; support?: string } };
      verification: { receipt: { ok: boolean }; conference: { ok: boolean } | null };
    };
    assert.equal(exp.verification.receipt.ok, true);
    assert.equal(exp.receipt.payload.cu.cu.units, '48000000');
    assert.match(exp.receipt.payload.config.circuitId, /^metering_v3@sha256:/);
    if (exp.conference.payload) { assert.equal(exp.verification.conference!.ok, true); assert.ok(exp.conference.payload.support, 'contract 1.1.0 support filled'); }

    // proof produced by the worker and registered on Besu
    assert.ok(await eventually(async () => (await db.pool.query("SELECT 1 FROM otk_outbox WHERE tenant_id = $1 AND operation_id = $2 AND kind = 'submit_onchain' AND state = 'done'", [T, OP])).rowCount === 1, 240_000, 1000), api.log.join('').slice(-4000));
    const sub = (await db.pool.query<{ payload: { result?: { txHash: string }; auth: { operationRef: string; authorizationDigest: string; bucket: { min: string; max: string }; commitment: string } } }>(
      "SELECT payload FROM otk_outbox WHERE tenant_id = $1 AND operation_id = $2 AND kind = 'submit_onchain'", [T, OP])).rows[0]!;
    const txHash = sub.payload.result!.txHash; // the worker merges the public result into the payload
    const reg = new ethers.Contract(deployment.domain.registry, REGISTRY_V3_SUBMIT_ABI as unknown as string[], rpc);
    assert.equal(String(await reg.getFunction('registeredDigest')(sub.payload.auth.operationRef)).toLowerCase(), sub.payload.auth.authorizationDigest.toLowerCase());
    assert.deepEqual([sub.payload.auth.bucket.min, sub.payload.auth.bucket.max], ['0', '999999999'], 'fixed 1000-CU window, closed interval [0, 10^9 − 1] micro-CU');
    assert.equal(exp.receipt.payload.publicCommitment, sub.payload.auth.commitment, 'receipt → commitment → authorization → proof → registry');

    // D2-G05 / INT-07 surface check on the real transaction: no exact usage, tenant or operation id
    const tx = (await rpc.getTransaction(txHash))!;
    const rc = (await rpc.getTransactionReceipt(txHash))!;
    const words = (hex: string) => hex.replace(/^0x/, '').match(/.{1,64}/g) ?? [];
    const pub = [...words(tx.data.slice(10)), ...rc.logs.flatMap((l) => [...l.topics.map((t) => t.slice(2)), ...words(l.data)])];
    for (const v of [48_000_000n, 48n, 120n]) assert.ok(!pub.includes(v.toString(16).padStart(64, '0')), `exact value ${v} in calldata/events`);
    const asText = Buffer.from(tx.data.slice(2), 'hex').toString('latin1') + rc.logs.map((l) => Buffer.from(l.data.slice(2), 'hex').toString('latin1')).join('');
    assert.ok(!asText.includes(T) && !asText.includes(OP), 'tenant/operation id not public');
    // provider-side or stdout logs never carry the opening or the operator key
    const log = api.log.join('');
    assert.ok(!log.includes(devKey('operator').slice(2)) && !log.includes(devKey('submitter').slice(2)), 'no key in logs');
    const opening = (await db.pool.query<{ o: { blinding: string } }>('SELECT opening AS o FROM otk_openings WHERE tenant_id = $1 AND operation_id = $2', [T, OP])).rows[0]!;
    assert.ok(!log.includes(String(opening.o.blinding)), 'no opening in logs');
    assert.equal(rc.status, 1);
    process.stdout.write(`# INT-02 tx ${txHash} block ${rc.blockNumber} gasUsed ${rc.gasUsed}\n`);
  });
});
