#!/usr/bin/env node
/**
 * D6-G01/G03 — verify zk/v3/MANIFEST.json against the files of this checkout.
 *
 *   node scripts/zk/v3_verify_manifest.mjs                 # hashes + ptau/zkey/vkey/verifier checks
 *   CIRCOM=<circom 2.1.6> node scripts/zk/v3_verify_manifest.mjs   # also recompiles the circuit
 *
 * Checks: every listed file hash (text normalized CRLF→LF, as the manifest records); circuitId ==
 * metering_v3@sha256:<r1cs>; phase 1 chain (powersOfTau.verify); zkey derived from r1cs + ptau
 * (zKey.verifyFromR1cs); vkey file == key embedded in the zkey; Solidity verifier regenerated from
 * the zkey == committed contract; optional recompilation reproduces r1cs/wasm/sym.
 * A valid chain shows the artifacts are mutually consistent. It says nothing about who held the
 * contribution randomness (see MANIFEST.label). Exit 1 on any mismatch.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { createRequire } from 'node:module';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const require = createRequire(path.join(ROOT, 'package.json'));
const snarkjs = require('snarkjs');
const P = (f) => path.join(ROOT, f);
const quiet = { info() {}, debug() {}, warn() {}, error: (m) => console.error(m) };
const TEXT_EXT = new Set(['.circom', '.sol', '.js', '.sym', '.json', '.md', '.txt']);
const hashOf = (f) => (TEXT_EXT.has(path.extname(f))
  ? createHash('sha256').update(readFileSync(f, 'utf8').replace(/\r\n/g, '\n')).digest('hex')
  : createHash('sha256').update(readFileSync(f)).digest('hex'));
const canon = (x) => JSON.stringify(x, (_k, v) => (v && typeof v === 'object' && !Array.isArray(v) ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, v[k]])) : v));

const m = JSON.parse(readFileSync(P('zk/v3/MANIFEST.json'), 'utf8'));
const checks = [];
const check = (name, ok, detail = '') => { checks.push({ name, ok: !!ok, detail }); };

for (const [f, h] of Object.entries(m.files)) {
  let got = null;
  try { got = hashOf(P(f)); } catch (e) { got = `missing: ${e.code}`; }
  check(`hash ${f}`, got === h, got === h ? '' : `got ${got}`);
}
{
  const w = /width=(\d+)CU:unit=microCU$/.exec(m.registry?.bucketPolicy ?? '');
  check('registry.bucketWidthUnits matches the width in the policy version', !!w && BigInt(w[1]) * 1_000_000n === BigInt(m.registry.bucketWidthUnits));
}
check('circuitId = metering_v3@sha256:<r1cs>', m.circuitId === `metering_v3@sha256:${hashOf(P('zk/v3/build/metering_v3.r1cs'))}`);

const ptau = P('zk/v3/setup/pot11_demo_final.ptau');
const r1cs = P('zk/v3/build/metering_v3.r1cs');
const zkey = P('zk/v3/keys/metering_v3_demo_final.zkey');
check('powersOfTau.verify', await snarkjs.powersOfTau.verify(ptau, quiet));
check('zKey.verifyFromR1cs', await snarkjs.zKey.verifyFromR1cs(r1cs, ptau, zkey, quiet));
const vk = await snarkjs.zKey.exportVerificationKey(zkey, quiet);
check('vkey file == zkey embedded key', canon(vk) === canon(JSON.parse(readFileSync(P('zk/v3/keys/metering_v3_demo_vkey.json'), 'utf8'))));
const tpl = readFileSync(P('node_modules/snarkjs/templates/verifier_groth16.sol.ejs'), 'utf8');
let sol = await snarkjs.zKey.exportSolidityVerifier(zkey, { groth16: tpl }, quiet);
sol = sol.replace('contract Groth16Verifier', 'contract MeteringVerifierV3Demo')
  .replace(/pragma solidity [^;]+;/, (x) => `${x}\n\n// GENERATED by scripts/zk/v3_demo_setup.mjs from zk/v3/keys/metering_v3_demo_final.zkey.\n// LOCAL DEMONSTRATIVE SETUP — single executor, not a ceremony. Do not edit by hand.`);
const committed = readFileSync(P('tools/hardhat/contracts/v3/MeteringVerifierV3Demo.sol'), 'utf8').replace(/\r\n/g, '\n');
check('Solidity verifier regenerated from zkey == committed', sol.replace(/\r\n/g, '\n') === committed);

if (process.env.CIRCOM) {
  const tmp = mkdtempSync(path.join(os.tmpdir(), 'otk-v3-recompile-'));
  try {
    execFileSync(process.env.CIRCOM, ['zk/circuits/metering_v3.circom', '--r1cs', '--wasm', '--sym', '--O1', '-l', 'zk/circuits', '-o', tmp], { cwd: ROOT, stdio: 'ignore' });
    for (const [built, listed] of [['metering_v3.r1cs', 'zk/v3/build/metering_v3.r1cs'], ['metering_v3_js/metering_v3.wasm', 'zk/v3/build/metering_v3_js/metering_v3.wasm'], ['metering_v3.sym', 'zk/v3/build/metering_v3.sym']]) {
      const got = hashOf(path.join(tmp, built));
      check(`recompile reproduces ${listed}`, got === m.files[listed], got === m.files[listed] ? '' : `got ${got}`);
    }
  } finally { rmSync(tmp, { recursive: true, force: true }); }
} else {
  check('recompile (skipped: CIRCOM not set)', true, 'NOT_RUN');
}

await globalThis.curve_bn128?.terminate();
const ok = checks.every((c) => c.ok);
console.log(JSON.stringify({ ok, circuitId: m.circuitId, label: m.label, checks }, null, 2));
process.exit(ok ? 0 : 1);
