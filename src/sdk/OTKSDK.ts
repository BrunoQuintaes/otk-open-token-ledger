/**
 * OTK SDK — Receipt Builder for Multi-Provider Metering
 *
 * Thin wrapper to construct RawReceipts and DualReceipts from provider responses.
 * Maps provider-specific data to canonical receipt schema.
 *
 * Part of U8.4.1 MVP (pre-U8.5, no on-chain submission yet).
 *
 * Who calls it: `src/proxy/ProxyGateway.ts` uses {@link buildRawReceipt}; the other builders are used by SDK
 * clients and tests. `submitReceipt`, `buildDualReceiptV2` and `OTKSDK.buildReceiptV2` make a network call to the
 * prover service (base URL from `opts.proverUrl`, else the `OTK_PROVER_URL` environment variable, read by
 * `ProverClient`); every builder signs with the caller's signer. No receipt is stored or sent on-chain here.
 *
 * @module src/sdk/OTKSDK
 */

import { ethers } from 'ethers';
import type { RawReceipt, DualReceipt, ZKReceipt, DualReceiptV2, ZKReceiptV2 } from '../types/receipt.js';
import { deriveEpoch, deriveUsage, deriveBuckets } from '../types/receipt.js';
import { canonicalHash, sign } from '../metering/SignatureManager.js';
import { computeKnownCu } from '../operations/knownCu.js';
import { ProverClient } from '../prover/ProverClient.js';

/**
 * Provider response metadata (normalized interface)
 *
 * This is what provider adapters should return after calling provider APIs.
 */
export interface ProviderResponse {
  provider: string;
  model: string;
  inputTokens: number;
  outputTokens: number;
  latencyMs: number;
  requestId: string;
  timestamp: number; // Unix seconds

  /** Optional session/context metadata */
  metadata?: {
    sessionId?: string;
    endpoint?: string;
    tags?: string[];
  };
}

/**
 * Cost normalization function type
 *
 * Maps provider-specific token counts to normalized cost units.
 * Example: costUnits = inputTokens * inputRate + outputTokens * outputRate
 */
export type CostNormalizer = (
  provider: string,
  model: string,
  inputTokens: number,
  outputTokens: number
) => number;

/**
 * Default cost normalizer (enterprise model with weighted pricing)
 *
 * Uses U5 enterprise cost weights (provider × model × tokens).
 *
 * @param provider - Provider ID.
 * @param model - Model ID.
 * @param inputTokens - Input tokens (non-negative integer).
 * @param outputTokens - Output tokens (non-negative integer).
 * @returns The exact cost units (CU) of the active weights.
 * @throws {Error} When the CU cannot be computed (unknown provider/model or invalid counts).
 */
export const defaultCostNormalizer: CostNormalizer = (
  provider: string,
  model: string,
  inputTokens: number,
  outputTokens: number
): number => {
  // S4 (D5-G04, N5): the exact server-side CU of the active weights (computeKnownCu → B's
  // computeCuFromTotals once the server wires it; legacy exact integer formula otherwise), never
  // the public bucket: a bucket rounds small consumption to 0 in the accounting
  const r = computeKnownCu({ provider, model, inputTokens, outputTokens });
  if (r.status !== 'computed') throw new Error(`CU not computable for ${provider}/${model}: ${r.detail}`);
  return r.costUnits;
};

/**
 * Build a RawReceipt from provider response
 *
 * @param response Provider response metadata
 * @param userId User identifier (pseudonymous ID for circuit)
 * @param nonce Anti-replay nonce (monotonic per user)
 * @param costNormalizer Optional cost normalization function
 * @returns Raw receipt ready for signing
 * @throws {Error} When the cost normalizer throws (the default one does for a non-computable CU).
 */
export function buildRawReceipt(
  response: ProviderResponse,
  userId: bigint,
  nonce: bigint,
  costNormalizer: CostNormalizer = defaultCostNormalizer
): RawReceipt {
  const costUnits = costNormalizer(
    response.provider,
    response.model,
    response.inputTokens,
    response.outputTokens
  );

  return {
    provider: response.provider,
    model: response.model,
    inputTokens: response.inputTokens,
    outputTokens: response.outputTokens,
    costUnits,
    latencyMs: response.latencyMs,
    timestamp: response.timestamp,
    requestId: response.requestId,
    userId,
    nonce,
    metadata: response.metadata,
  };
}

/**
 * Build a DualReceipt (Raw + ZK) from provider response
 *
 * MVP version: ZK proof is placeholder (to be generated by prover in U8.5+).
 * This function focuses on the raw receipt + signature part.
 *
 * @param response Provider response metadata
 * @param userId User identifier
 * @param nonce Anti-replay nonce
 * @param signer Ethers.js Wallet or Signer for signing raw receipt
 * @param maxUsage Maximum allowed usage for this epoch (ZK constraint)
 * @param costNormalizer Optional cost normalization function
 * @returns Dual receipt with raw + signature + placeholder ZK
 */
export async function buildDualReceipt(
  response: ProviderResponse,
  userId: bigint,
  nonce: bigint,
  signer: ethers.Wallet | ethers.Signer,
  maxUsage: bigint,
  costNormalizer?: CostNormalizer
): Promise<DualReceipt> {
  // Build raw receipt
  const raw = buildRawReceipt(response, userId, nonce, costNormalizer);

  // Sign raw receipt
  const signature = await sign(raw, signer);

  // Derive ZK fields from raw receipt (Dual Receipt Model binding)
  const epoch = deriveEpoch(raw.timestamp);

  // Placeholder ZK receipt (commitment 0n): the SDK does not compute Poseidon(userId, usage, nonce, epoch) (proof generation is separate, happens in prover)
  const zk: ZKReceipt = {
    commitment: 0n, // Placeholder: would be Poseidon(userId, usage, nonce, epoch)
    epoch,
    maxUsage,
    proof: {
      pi_a: [0n, 0n],
      pi_b: [
        [0n, 0n],
        [0n, 0n],
      ],
      pi_c: [0n, 0n],
    },
  };

  return {
    raw,
    signature,
    zk,
  };
}

/**
 * Validate Dual Receipt binding (Raw ↔ ZK consistency)
 *
 * Ensures the ZK receipt fields are correctly derived from the raw receipt.
 *
 * @param dual Dual receipt to validate
 * @returns True if binding is consistent, false otherwise
 */
export function validateDualReceiptBinding(dual: DualReceipt): boolean {
  // Derive expected ZK fields from raw receipt
  const expectedEpoch = deriveEpoch(dual.raw.timestamp);
  const expectedUsage = deriveUsage(dual.raw);

  // Check epoch match
  if (dual.zk.epoch !== expectedEpoch) {
    console.error(
      `Epoch mismatch: ZK=${dual.zk.epoch}, expected=${expectedEpoch}`
    );
    return false;
  }

  // Check usage derivation (usage should be <= maxUsage, but we don't enforce here)
  // Just log for debugging
  if (expectedUsage > dual.zk.maxUsage) {
    console.warn(
      `Usage exceeds maxUsage: usage=${expectedUsage}, maxUsage=${dual.zk.maxUsage}`
    );
  }

  // Signature hash should match canonical hash of raw receipt
  const expectedHash = canonicalHash(dual.raw);
  if (dual.signature.rawHash !== expectedHash) {
    console.error(
      `Signature hash mismatch: signature=${dual.signature.rawHash}, expected=${expectedHash}`
    );
    return false;
  }

  return true;
}

/**
 * Options for submitReceipt() (S5.1 — ZK v2 SDK integration)
 */
export interface SubmitReceiptOpts {
  /** Circuit version to use (default: 'v2') */
  circuitVersion?: 'v1' | 'v2';
  /** v2: lower usage bucket bound (public signal) */
  minUsageBucket?: bigint;
  /** v2 / v1: upper usage bucket / maxUsage (public signal) */
  maxUsageBucket?: bigint;
  /** v1 compat alias for maxUsageBucket */
  maxUsage?: bigint;
  /** ProverDaemon base URL (default: OTK_PROVER_URL || http://localhost:3001) */
  proverUrl?: string;
  /** Proof polling options */
  pollTimeoutMs?: number;
}

/**
 * Build a DualReceipt with a REAL ZK proof from ProverDaemon (S5.1)
 *
 * Unlike buildDualReceipt() which uses a placeholder proof, this function
 * calls ProverDaemon via ProverClient and returns the actual Groth16 proof.
 *
 * pubSignals order for v2 (CLAUDE.md §8):
 *   [0] commitment (Poseidon hash — OUTPUT comes first in snarkjs Groth16)
 *   [1] epoch
 *   [2] minUsageBucket
 *   [3] maxUsageBucket
 *
 * @param response  Provider response metadata
 * @param userId    User identifier
 * @param nonce     Anti-replay nonce
 * @param signer    Ethers.js Wallet or Signer for signing raw receipt
 * @param opts      Circuit version + bucket bounds + prover URL
 * @param costNormalizer - Optional cost normalization function (default {@link defaultCostNormalizer}).
 * @returns The signed raw receipt plus the ZK part built from the prover's proof and public signals.
 * @throws {Error} When the proof job does not end with status `done` (rejected promise), and any error of
 *   the signer, the cost normalizer or the prover client.
 */
export async function submitReceipt(
  response: ProviderResponse,
  userId: bigint,
  nonce: bigint,
  signer: ethers.Wallet | ethers.Signer,
  opts: SubmitReceiptOpts = {},
  costNormalizer: CostNormalizer = defaultCostNormalizer,
): Promise<DualReceipt> {
  const circuitVersion = opts.circuitVersion ?? 'v2';
  const raw = buildRawReceipt(response, userId, nonce, costNormalizer);
  const signature = await sign(raw, signer);
  const epoch = deriveEpoch(raw.timestamp);
  const usage = deriveUsage(raw);

  // Build ProofInput based on circuit version
  const proofInput = {
    userId: userId.toString(),
    usage: usage.toString(),
    nonce: nonce.toString(),
    epoch: epoch.toString(),
    circuitVersion,
    ...(circuitVersion === 'v2'
      ? {
          minUsageBucket: (opts.minUsageBucket ?? 0n).toString(),
          maxUsageBucket: (opts.maxUsageBucket ?? opts.maxUsage ?? usage + 1n).toString(),
        }
      : {
          maxUsage: (opts.maxUsage ?? opts.maxUsageBucket ?? usage + 1n).toString(),
        }),
  };

  const client = new ProverClient(opts.proverUrl);
  const job = await client.prove(proofInput, { timeoutMs: opts.pollTimeoutMs });

  if (job.status !== 'done' || !job.result) {
    throw new Error(
      `submitReceipt: proof job ${job.jobId} ended with status=${job.status}` +
        (job.error ? ` — ${job.error}` : ''),
    );
  }

  const { proof, publicSignals } = job.result;

  // Parse publicSignals per circuit version
  const commitment = BigInt(publicSignals[0] ?? '0');
  // epoch from pubSignals[1], maxUsage/maxUsageBucket from [2] (v1) or [3] (v2)
  const maxUsagePub =
    circuitVersion === 'v2'
      ? BigInt(publicSignals[3] ?? '0')
      : BigInt(publicSignals[2] ?? '0');

  const zk: ZKReceipt = {
    commitment,
    epoch,
    maxUsage: maxUsagePub,
    proof: {
      pi_a: [BigInt(proof.pi_a[0] ?? '0'), BigInt(proof.pi_a[1] ?? '0')],
      pi_b: [
        [BigInt(proof.pi_b[0]?.[0] ?? '0'), BigInt(proof.pi_b[0]?.[1] ?? '0')],
        [BigInt(proof.pi_b[1]?.[0] ?? '0'), BigInt(proof.pi_b[1]?.[1] ?? '0')],
      ],
      pi_c: [BigInt(proof.pi_c[0] ?? '0'), BigInt(proof.pi_c[1] ?? '0')],
    },
  };

  return { raw, signature, zk };
}

/**
 * Build a DualReceiptV2 (Raw + ZKv2 range proof) with a REAL proof from ProverDaemon.
 *
 * Uses metering_v2.circom (range proof) via ProverClient.
 * pubSignals order: [commitment, epoch, minUsageBucket, maxUsageBucket]
 *
 * @param response       Provider response metadata
 * @param userId         User identifier
 * @param nonce          Anti-replay nonce
 * @param signer         Ethers.js Wallet or Signer
 * @param minUsageBucket Lower bucket bound (inclusive). Pass 0n to auto-derive.
 * @param maxUsageBucket Upper bucket bound (inclusive). Pass 0n to auto-derive.
 * @param opts           ProverDaemon URL + poll timeout
 * @since Wave 5 (W5-5A01 / S6.1)
 * @param costNormalizer - Optional cost normalization function (default {@link defaultCostNormalizer}).
 * @returns The signed raw receipt plus the v2 ZK part (range proof).
 * @throws {Error} When the proof job does not end with status `done` (rejected promise), and any error of
 *   the signer, the cost normalizer or the prover client.
 */
export async function buildDualReceiptV2(
  response: ProviderResponse,
  userId: bigint,
  nonce: bigint,
  signer: ethers.Wallet | ethers.Signer,
  minUsageBucket: bigint = 0n,
  maxUsageBucket: bigint = 0n,
  opts: Pick<SubmitReceiptOpts, 'proverUrl' | 'pollTimeoutMs'> = {},
  costNormalizer: CostNormalizer = defaultCostNormalizer,
): Promise<DualReceiptV2> {
  const raw = buildRawReceipt(response, userId, nonce, costNormalizer);
  const signature = await sign(raw, signer);
  const epoch = deriveEpoch(raw.timestamp);
  const usage = deriveUsage(raw);

  // Auto-derive buckets if not provided
  const buckets = (minUsageBucket === 0n && maxUsageBucket === 0n)
    ? deriveBuckets(usage)
    : { minUsageBucket, maxUsageBucket };

  const proofInput = {
    userId: userId.toString(),
    usage: usage.toString(),
    nonce: nonce.toString(),
    epoch: epoch.toString(),
    circuitVersion: 'v2' as const,
    minUsageBucket: buckets.minUsageBucket.toString(),
    maxUsageBucket: buckets.maxUsageBucket.toString(),
  };

  const client = new ProverClient(opts.proverUrl);
  const job = await client.prove(proofInput, { timeoutMs: opts.pollTimeoutMs });

  if (job.status !== 'done' || !job.result) {
    throw new Error(
      `buildDualReceiptV2: proof job ${job.jobId} ended with status=${job.status}` +
        (job.error ? ` — ${job.error}` : ''),
    );
  }

  const { proof, publicSignals } = job.result;

  const zk: ZKReceiptV2 = {
    commitment: BigInt(publicSignals[0] ?? '0'),
    epoch,
    minUsageBucket: BigInt(publicSignals[2] ?? buckets.minUsageBucket.toString()),
    maxUsageBucket: BigInt(publicSignals[3] ?? buckets.maxUsageBucket.toString()),
    proof: {
      pi_a: [BigInt(proof.pi_a[0] ?? '0'), BigInt(proof.pi_a[1] ?? '0')],
      pi_b: [
        [BigInt(proof.pi_b[0]?.[0] ?? '0'), BigInt(proof.pi_b[0]?.[1] ?? '0')],
        [BigInt(proof.pi_b[1]?.[0] ?? '0'), BigInt(proof.pi_b[1]?.[1] ?? '0')],
      ],
      pi_c: [BigInt(proof.pi_c[0] ?? '0'), BigInt(proof.pi_c[1] ?? '0')],
    },
  };

  return { raw, signature, zk };
}

/**
 * OTK SDK class (stateful wrapper for convenience)
 *
 * Maintains user context (userId, nonce counter, signer) and provides
 * high-level methods for building receipts.
 *
 * IMPORTANT (ADR-0004): Nonce MUST be synced with on-chain state before use.
 * Use syncNonce() to update from Registry, or query before each buildReceipt().
 */
export class OTKSDK {
  private userId: bigint;
  private nonceCounter: bigint;
  private signer: ethers.Wallet | ethers.Signer;
  private costNormalizer: CostNormalizer;

  constructor(
    userId: bigint,
    initialNonce: bigint,
    signer: ethers.Wallet | ethers.Signer,
    costNormalizer: CostNormalizer = defaultCostNormalizer
  ) {
    this.userId = userId;
    this.nonceCounter = initialNonce;
    this.signer = signer;
    this.costNormalizer = costNormalizer;
  }

  /**
   * Sync nonce with external source (e.g., Receipt Registry on-chain state)
   *
   * REQUIRED before buildReceipt() to ensure nonce matches Registry expectation.
   * See ADR-0004 for nonce anti-replay model.
   *
   * @param nonce Current nonce from Registry or external tracker
   */
  syncNonce(nonce: bigint): void {
    this.nonceCounter = nonce;
  }

  /**
   * Build and sign a dual receipt from provider response
   *
   * Automatically increments nonce after building.
   *
   * @param response Provider response
   * @param maxUsage Maximum allowed usage for this epoch
   * @returns Signed dual receipt
   */
  async buildReceipt(
    response: ProviderResponse,
    maxUsage: bigint
  ): Promise<DualReceipt> {
    const dual = await buildDualReceipt(
      response,
      this.userId,
      this.nonceCounter,
      this.signer,
      maxUsage,
      this.costNormalizer
    );

    // Increment nonce for next receipt
    this.nonceCounter += 1n;

    return dual;
  }

  /**
   * Build a DualReceiptV2 (range proof, metering_v2.circom) from provider response.
   *
   * Calls ProverDaemon to generate a real Groth16 v2 proof.
   * Buckets are auto-derived from costUnits if not provided (step=300 CU).
   *
   * @param response       Provider response
   * @param minUsageBucket Lower bucket bound (0n = auto-derive)
   * @param maxUsageBucket Upper bucket bound (0n = auto-derive)
   * @param opts           ProverDaemon URL + poll timeout
   * @returns DualReceiptV2 with range-proof ZK component
   * @since Wave 5 (W5-5A01 / S6.1)
   */
  async buildReceiptV2(
    response: ProviderResponse,
    minUsageBucket: bigint = 0n,
    maxUsageBucket: bigint = 0n,
    opts: Pick<SubmitReceiptOpts, 'proverUrl' | 'pollTimeoutMs'> = {},
  ): Promise<DualReceiptV2> {
    const dual = await buildDualReceiptV2(
      response,
      this.userId,
      this.nonceCounter,
      this.signer,
      minUsageBucket,
      maxUsageBucket,
      opts,
      this.costNormalizer,
    );

    // Increment nonce for next receipt
    this.nonceCounter += 1n;

    return dual;
  }

  /**
   * Get current nonce (next value to be used)
   * @returns The nonce the next built receipt will use.
   */
  getCurrentNonce(): bigint {
    return this.nonceCounter;
  }

  /**
   * Get user ID
   * @returns The user ID given at construction.
   */
  getUserId(): bigint {
    return this.userId;
  }
}
